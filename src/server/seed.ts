export async function seed(db: Db) {
  for (const [
    id,
    name,
    category,
    description,
    priceCents,
    costCents,
    minMarginBps,
    stock,
  ] of rows) {
    if (floorPrice(costCents, minMarginBps) > priceCents)
      throw Error("Margem inválida");
    await db.product.upsert({
      where: { id },
      update: {},
      create: {
        id,
        name,
        category,
        description,
        priceCents,
        costCents,
        minMarginBps,
        stock,
      },
    });
  }
}
if (require.main === module) {
  const db = new Db();
  seed(db).finally(() => db.$disconnect());
}
